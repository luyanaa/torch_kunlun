import pytest
import torch
import torch.nn.functional as F

torch_kunlun = pytest.importorskip("torch_kunlun")
kunlun = torch_kunlun.kunlun

pytestmark = pytest.mark.skipif(
    not kunlun.is_available(),
    reason="Kunlun K200 device is not available",
)


def _ones(x):
    out = torch.empty_like(x)
    out.fill_(1.0)
    return out


def test_losses_forward_backward():
    logits = torch.randn(6, 5, dtype=torch.float16)
    target = torch.tensor([0, 2, 4, 1, 3, 0], dtype=torch.int64)
    logp = F.log_softmax(logits, -1)
    lr = logp.clone().requires_grad_()
    loss_r = F.nll_loss(lr, target)
    loss_r.backward()
    lk = logp.to("kunlun").requires_grad_()
    loss_k = F.nll_loss(lk, target.to("kunlun"))
    loss_k.backward()
    kunlun.synchronize()
    assert torch.allclose(loss_k.cpu(), loss_r.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(lk.grad.cpu(), lr.grad, atol=5e-2, rtol=5e-2)

    x = torch.rand(8, dtype=torch.float16) * 0.8 + 0.1
    y = torch.rand(8, dtype=torch.float16)
    xr, yr = x.clone().requires_grad_(), y.clone()
    out_r = F.binary_cross_entropy(xr, yr)
    out_r.backward()
    xk = x.to("kunlun").requires_grad_()
    out_k = F.binary_cross_entropy(xk, y.to("kunlun"))
    out_k.backward()
    kunlun.synchronize()
    assert torch.allclose(out_k.cpu(), out_r.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(xk.grad.cpu(), xr.grad, atol=5e-2, rtol=5e-2)

    logits = torch.randn(8, dtype=torch.float16)
    y = (torch.rand(8, dtype=torch.float16) > 0.5).half()
    lr, yr = logits.clone().requires_grad_(), y.clone()
    out_r = F.binary_cross_entropy_with_logits(lr, yr)
    out_r.backward()
    lk = logits.to("kunlun").requires_grad_()
    out_k = F.binary_cross_entropy_with_logits(lk, y.to("kunlun"))
    out_k.backward()
    kunlun.synchronize()
    assert torch.allclose(out_k.cpu(), out_r.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(lk.grad.cpu(), lr.grad, atol=5e-2, rtol=5e-2)

    for fn in (
        lambda a, b: F.l1_loss(a, b),
        lambda a, b: F.smooth_l1_loss(a, b, beta=0.5),
        lambda a, b: F.huber_loss(a, b, delta=0.5),
    ):
        a = torch.randn(8, dtype=torch.float16)
        b = torch.randn(8, dtype=torch.float16)
        ar, br = a.clone().requires_grad_(), b.clone().requires_grad_()
        out_r = fn(ar, br)
        out_r.backward()
        ak = a.to("kunlun").requires_grad_()
        bk = b.to("kunlun").requires_grad_()
        out_k = fn(ak, bk)
        out_k.backward()
        kunlun.synchronize()
        assert torch.allclose(out_k.cpu(), out_r.detach(), atol=5e-2, rtol=5e-2)
        assert torch.allclose(ak.grad.cpu(), ar.grad, atol=5e-2, rtol=5e-2)
        assert torch.allclose(bk.grad.cpu(), br.grad, atol=5e-2, rtol=5e-2)

    logp = torch.log_softmax(torch.randn(4, 3, dtype=torch.float16), -1)
    target = torch.softmax(torch.randn(4, 3, dtype=torch.float16), -1)
    lr = logp.clone().requires_grad_()
    out_r = F.kl_div(lr, target, reduction="batchmean")
    out_r.backward()
    lk = logp.to("kunlun").requires_grad_()
    out_k = F.kl_div(lk, target.to("kunlun"), reduction="batchmean")
    out_k.backward()
    kunlun.synchronize()
    assert torch.allclose(out_k.cpu(), out_r.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(lk.grad.cpu(), lr.grad, atol=5e-2, rtol=5e-2)


def test_norm_and_pool_extra():
    x = torch.randn(2, 6, 4, 4, dtype=torch.float16)
    g = torch.randn(6, dtype=torch.float16)
    b = torch.randn(6, dtype=torch.float16)
    xr, gr, br = x.clone().requires_grad_(), g.clone().requires_grad_(), b.clone().requires_grad_()
    yr = F.group_norm(xr, 3, gr, br, 1e-5)
    yr.backward(_ones(yr))
    xk = x.to("kunlun").requires_grad_()
    gk = g.to("kunlun").requires_grad_()
    bk = b.to("kunlun").requires_grad_()
    yk = F.group_norm(xk, 3, gk, bk, 1e-5)
    yk.backward(_ones(yk))
    kunlun.synchronize()
    assert torch.allclose(yk.cpu(), yr.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(xk.grad.cpu(), xr.grad, atol=5e-2, rtol=5e-2)
    assert torch.allclose(gk.grad.cpu(), gr.grad, atol=5e-2, rtol=5e-2)
    assert torch.allclose(bk.grad.cpu(), br.grad, atol=5e-2, rtol=5e-2)

    x = torch.randn(2, 4, 4, 4, dtype=torch.float16)
    xr = x.clone().requires_grad_()
    yr = F.instance_norm(xr)
    yr.backward(_ones(yr))
    xk = x.to("kunlun").requires_grad_()
    yk = F.instance_norm(xk)
    yk.backward(_ones(yk))
    kunlun.synchronize()
    assert torch.allclose(yk.cpu(), yr.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(xk.grad.cpu(), xr.grad, atol=5e-2, rtol=5e-2)

    x = torch.randn(2, 3, 6, 6, dtype=torch.float16)
    xr = x.clone().requires_grad_()
    yr = F.adaptive_max_pool2d(xr, (2, 2))
    yr.backward(_ones(yr))
    xk = x.to("kunlun").requires_grad_()
    yk = F.adaptive_max_pool2d(xk, (2, 2))
    yk.backward(_ones(yk))
    kunlun.synchronize()
    assert torch.allclose(yk.cpu(), yr.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(xk.grad.cpu(), xr.grad, atol=5e-2, rtol=5e-2)

    x = torch.randn(2, 2, 4, 4, 4, dtype=torch.float16)
    xr = x.clone().requires_grad_()
    yr = F.avg_pool3d(xr, 2, 2)
    yr.backward(_ones(yr))
    xk = x.to("kunlun").requires_grad_()
    yk = F.avg_pool3d(xk, 2, 2)
    yk.backward(_ones(yk))
    kunlun.synchronize()
