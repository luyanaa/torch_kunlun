def test_matmul_baddbmm_extra():
    for shape in [(3, 4), (2, 3, 4), (2, 2, 3, 4)]:
        a = torch.randn(*shape, dtype=torch.float16)
        bshape = shape[:-2] + (shape[-1], 5) if len(shape) == 4 else shape[:-1] + (5,)
        b = torch.randn(*bshape, dtype=torch.float16)
        ar, br = a.clone().requires_grad_(), b.clone().requires_grad_()
        cr = torch.matmul(ar, br)
        cr.backward(_ones(cr))
        ak = a.to("kunlun").requires_grad_()
        bk = b.to("kunlun").requires_grad_()
        ck = torch.matmul(ak, bk)
        ck.backward(_ones(ck))
        kunlun.synchronize()
        assert torch.allclose(ck.cpu(), cr.detach(), atol=5e-2, rtol=5e-2)
        assert torch.allclose(ak.grad.cpu(), ar.grad, atol=5e-2, rtol=5e-2)
        assert torch.allclose(bk.grad.cpu(), br.grad, atol=5e-2, rtol=5e-2)

    a = torch.randn(2, 3, 4, dtype=torch.float16)
    b = torch.randn(2, 4, 5, dtype=torch.float16)
    c = torch.randn(2, 3, 5, dtype=torch.float16)
    ar, br, cr = a.clone().requires_grad_(), b.clone().requires_grad_(), c.clone().requires_grad_()
    out_r = torch.baddbmm(cr, ar, br, beta=0.5, alpha=0.7)
    out_r.backward(_ones(out_r))
    ak = a.to("kunlun").requires_grad_()
    bk = b.to("kunlun").requires_grad_()
    ck = c.to("kunlun").requires_grad_()
    out_k = torch.baddbmm(ck, ak, bk, beta=0.5, alpha=0.7)
    out_k.backward(_ones(out_k))
    kunlun.synchronize()
    assert torch.allclose(out_k.cpu(), out_r.detach(), atol=5e-2, rtol=5e-2)
    assert torch.allclose(ak.grad.cpu(), ar.grad, atol=5e-2, rtol=5e-2)
    assert torch.allclose(bk.grad.cpu(), br.grad, atol=5e-2, rtol=5e-2)
    assert torch.allclose(ck.grad.cpu(), cr.grad, atol=5e-2, rtol=5e-2)


def test_conv1d_rms_norm_autograd():
    x = torch.randn(2, 3, 8, dtype=torch.float16)
